#!/usr/bin/env bash
set -euo pipefail

# Test suite for Knot Deskflow KVM Module & Client Runner (ISSUE-09 / ISSUE-10)
export KNOT_ROOT="$(cd "$(dirname "$(readlink -f "${BASH_SOURCE[0]}")")/.." && pwd)"

echo "=== [Test 1] Bash Syntax Verification ==="
bash -n "$KNOT_ROOT/core/modules/deskflow.sh"
echo "  -> deskflow.sh syntax: OK"

echo "=== [Test 2] Deskflow Compiler Integration (deskflow_compile_server_config) ==="
TMP_TEST_DIR="$(mktemp -d)"
trap 'rm -rf "$TMP_TEST_DIR"' EXIT

export HOME="$TMP_TEST_DIR/home"
export KNOT_RUNTIME_DIR="$TMP_TEST_DIR/run"
mkdir -p "$HOME/.config/Deskflow" "$HOME/.local/state/knot" "$HOME/.config/knot/swarms/testswarm/nodes" "$KNOT_RUNTIME_DIR"

# Setup test topology
cat << 'TOPO_EOF' > "$HOME/.config/knot/swarms/testswarm/topology.json"
{
  "anchor": "desktop",
  "screens": ["desktop", "laptop"],
  "layout": {
    "desktop": {
      "left": {
        "node": "laptop",
        "span": [60, 100]
      }
    }
  }
}
TOPO_EOF

cat << 'NODE1_EOF' > "$HOME/.config/knot/swarms/testswarm/nodes/desktop.json"
{
  "id": "desktop",
  "hostname": "test-anchor",
  "role": "anchor",
  "display": {"resolution": "2560x1440"}
}
NODE1_EOF

cat << 'NODE2_EOF' > "$HOME/.config/knot/swarms/testswarm/nodes/laptop.json"
{
  "id": "laptop",
  "hostname": "test-strand",
  "role": "strand",
  "display": {"resolution": "1920x1080"}
}
NODE2_EOF

# Set active swarm
echo "testswarm" > "$HOME/.local/state/knot/active_swarm"

# Source deskflow module
# Stub autounlock_configure and systemctl to avoid system modifications
autounlock_configure() { return 0; }
systemctl() { return 0; }
sudo() { "$@"; }

# Test deskflow_compile_server_config
source "$KNOT_ROOT/core/modules/deskflow.sh"

deskflow_compile_server_config "unlocked"
CONF_FILE="$HOME/.config/Deskflow/deskflow-server.conf"
if [ ! -f "$CONF_FILE" ]; then
  echo "Error: deskflow-server.conf not created!" >&2
  exit 1
fi

grep -q "test-anchor:" "$CONF_FILE"
grep -q "test-strand:" "$CONF_FILE"
grep -q "left(60,100) = test-strand(0,100)" "$CONF_FILE"
grep -q "right(0,100) = test-anchor(60,100)" "$CONF_FILE"
echo "  -> deskflow_compile_server_config generated correct reciprocal configuration: OK"

# Test locked mode
deskflow_compile_server_config "locked"
grep -q "test-anchor:" "$CONF_FILE"
anchor_links="$(awk '/test-anchor:/{flag=1; next} /^[[:space:]]*[a-zA-Z0-9_-]+:/{flag=0} flag && /=/{print}' "$CONF_FILE")"
if [ -n "$anchor_links" ]; then
  echo "Error: locked mode did not omit anchor outbound links: $anchor_links" >&2
  exit 1
fi
echo "  -> deskflow_compile_server_config locked mode confines cursor: OK"

# Test backward compatible deskflow_write_server_conf
deskflow_write_server_conf "unlocked"
grep -q "left(60,100) = test-strand(0,100)" "$CONF_FILE"
echo "  -> deskflow_write_server_conf alias: OK"

echo "=== [Test 3] Deskflow Client Runner Lifecycle ==="
CLIENT_RUNNER="$TMP_TEST_DIR/bin/knot-deskflow-client"
mkdir -p "$(dirname "$CLIENT_RUNNER")"

# Extract client runner script from deskflow.sh deploy section
sed -n '/RUNNER_EOF'\''/,/RUNNER_EOF/p' "$KNOT_ROOT/core/modules/deskflow.sh" | sed '1d;$d' > "$CLIENT_RUNNER"
chmod +x "$CLIENT_RUNNER"
bash -n "$CLIENT_RUNNER"
echo "  -> client runner script syntax: OK"

# 3a. Standalone mode (active_swarm=none)
echo "none" > "$HOME/.local/state/knot/active_swarm"
# Provide fake knot CLI
export PATH="$TMP_TEST_DIR/bin:$PATH"
cat << 'KNOT_EOF' > "$TMP_TEST_DIR/bin/knot"
#!/usr/bin/env bash
exit 0
KNOT_EOF
chmod +x "$TMP_TEST_DIR/bin/knot"

STANDALONE_OUT="$("$CLIENT_RUNNER")"
if ! echo "$STANDALONE_OUT" | grep -q "Active swarm is none"; then
  echo "Error: Expected graceful standalone exit, got: $STANDALONE_OUT" >&2
  exit 1
fi
echo "  -> Standalone mode clean exit: OK"

# 3b. Stop action
STOP_OUT="$("$CLIENT_RUNNER" stop)"
echo "  -> Client runner stop action: OK"

# 3c. Connected mode resolution
echo "testswarm" > "$HOME/.local/state/knot/active_swarm"
cat << 'SWARM_EOF' > "$HOME/.config/knot/swarms/testswarm/swarm.conf"
ANCHOR_ID="desktop"
ANCHOR_HOST="test-anchor"
SWARM_NAME="Test Swarm"
SWARM_EOF

# Provide mock knot resolve
cat << 'RESOLVE_EOF' > "$TMP_TEST_DIR/bin/knot"
#!/usr/bin/env bash
if [ "$1" = "resolve" ]; then
  echo "10.0.0.42"
  exit 0
fi
exit 1
RESOLVE_EOF
chmod +x "$TMP_TEST_DIR/bin/knot"

# Mock deskflow-core to verify invocation and config
cat << 'DF_EOF' > "$TMP_TEST_DIR/bin/deskflow-core"
#!/usr/bin/env bash
echo "deskflow-core invoked with: $*"
exit 0
DF_EOF
chmod +x "$TMP_TEST_DIR/bin/deskflow-core"

CLIENT_EXEC_OUT="$("$CLIENT_RUNNER")"
CLIENT_CONF="$HOME/.config/Deskflow/Deskflow.conf"
if [ ! -f "$CLIENT_CONF" ]; then
  echo "Error: Deskflow.conf not generated by client runner!" >&2
  exit 1
fi

grep -q "remoteHost=10.0.0.42" "$CLIENT_CONF"
echo "  -> Dynamic Anchor target resolution and config generation: OK"
echo "  -> Client exec invocation: OK"

echo "=== [Test 4] Deskflow Server Runner KVM Lock & Mute Integration ==="
SERVER_RUNNER="$TMP_TEST_DIR/bin/knot-deskflow-server"
cp "$CLIENT_RUNNER" "$SERVER_RUNNER"
chmod +x "$SERVER_RUNNER"

# Configure test swarm where current host is anchor
CURRENT_HOST="$(uname -n)"
if [ -r /proc/sys/kernel/hostname ]; then
  CURRENT_HOST="$(tr -d '[:space:]' < /proc/sys/kernel/hostname)"
fi

cat << SWARM_EOF > "$HOME/.config/knot/swarms/testswarm/swarm.conf"
ANCHOR_ID="$CURRENT_HOST"
ANCHOR_HOST="$CURRENT_HOST"
SWARM_NAME="Test Swarm"
SWARM_EOF

# Setup node manifests with CURRENT_HOST as anchor
cat << NODE_EOF > "$HOME/.config/knot/swarms/testswarm/nodes/${CURRENT_HOST}.json"
{
  "id": "${CURRENT_HOST}",
  "hostname": "${CURRENT_HOST}",
  "role": "anchor",
  "display": {"resolution": "2560x1440"}
}
NODE_EOF

cat << TOPO_EOF > "$HOME/.config/knot/swarms/testswarm/topology.json"
{
  "anchor": "${CURRENT_HOST}",
  "screens": ["${CURRENT_HOST}", "test-strand"],
  "layout": {
    "${CURRENT_HOST}": {
      "left": {
        "node": "test-strand",
        "span": [0, 100]
      }
    }
  }
}
TOPO_EOF

# 4a. Run in unlocked mode
echo "unlocked" > "$HOME/.local/state/knot/kvm_lock"
"$SERVER_RUNNER"
SERVER_CONF="$HOME/.config/Deskflow/deskflow-server.conf"
if [ ! -f "$SERVER_CONF" ]; then
  echo "Error: deskflow-server.conf not generated by server runner!" >&2
  exit 1
fi
grep -q "${CURRENT_HOST}:" "$SERVER_CONF"
grep -q "test-strand:" "$SERVER_CONF"
grep -q "left(0,100) = test-strand(0,100)" "$SERVER_CONF"
echo "  -> Server runner compiles unlocked layout with outbound links: OK"

# 4b. Run in locked mode
echo "locked" > "$HOME/.local/state/knot/kvm_lock"
"$SERVER_RUNNER"
server_anchor_links="$(awk -v host="${CURRENT_HOST}:" '$0 ~ host {flag=1; next} /^[[:space:]]*[a-zA-Z0-9_-]+:/{flag=0} flag && /=/{print}' "$SERVER_CONF")"
if [ -n "$server_anchor_links" ]; then
  echo "Error: Server runner in locked mode did not omit anchor outbound links: $server_anchor_links" >&2
  exit 1
fi
echo "  -> Server runner respects kvm_lock and confines cursor in locked mode: OK"

# 4c. Test mute node in server runner
echo "unlocked" > "$HOME/.local/state/knot/kvm_lock"
touch "$HOME/.local/state/knot/vmon_muted_deskflow_test-strand"
"$SERVER_RUNNER"
server_muted_links="$(awk -v host="${CURRENT_HOST}:" '$0 ~ host {flag=1; next} /^[[:space:]]*[a-zA-Z0-9_-]+:/{flag=0} flag && /=/{print}' "$SERVER_CONF")"
if [ -n "$server_muted_links" ]; then
  echo "Error: Server runner did not omit links to muted node: $server_muted_links" >&2
  exit 1
fi
rm -f "$HOME/.local/state/knot/vmon_muted_deskflow_test-strand"
echo "  -> Server runner respects vmon_muted_deskflow: OK"

# 4d. Test compiler resolution when KNOT_ROOT is unset (symlinked knot in PATH)
rm -f "$SERVER_CONF"
MOCK_BIN_DIR="$TMP_TEST_DIR/mock_bin"
mkdir -p "$MOCK_BIN_DIR"
ln -sf "$KNOT_ROOT/bin/knot" "$MOCK_BIN_DIR/knot"
PATH="$MOCK_BIN_DIR:$PATH" env -u KNOT_ROOT "$SERVER_RUNNER"
if [ ! -f "$SERVER_CONF" ]; then
  echo "Error: Server runner failed to resolve compiler when KNOT_ROOT was unset!" >&2
  exit 1
fi
echo "  -> Server runner resolves compiler via symlinked knot when KNOT_ROOT is unset: OK"

echo "=== [Test 5] deskflow_set_lock flock Concurrency Guard & State Transition ==="
echo "unlocked" > "$HOME/.local/state/knot/kvm_lock"
deskflow_set_lock "locked"
if [ "$(deskflow_get_lock)" != "locked" ]; then
  echo "Error: deskflow_set_lock failed to set locked state" >&2
  exit 1
fi
echo "  -> deskflow_set_lock locked transition: OK"

deskflow_set_lock "toggle"
if [ "$(deskflow_get_lock)" != "unlocked" ]; then
  echo "Error: deskflow_set_lock failed to toggle to unlocked state" >&2
  exit 1
fi
echo "  -> deskflow_set_lock toggle transition: OK"

# Test rejection of invalid state
set +e
deskflow_set_lock "invalid_state_xyz"
rc=$?
set -e
if [ $rc -eq 0 ]; then
  echo "Error: deskflow_set_lock should have rejected invalid target state" >&2
  exit 1
fi
if [ "$(deskflow_get_lock)" != "unlocked" ]; then
  echo "Error: deskflow_set_lock mutated state on invalid input" >&2
  exit 1
fi
echo "  -> deskflow_set_lock rejects invalid state: OK"

# Test non-blocking flock debouncing
LOCK_FILE="$HOME/.local/state/knot/kvm_lock.lock"
exec 9>"$LOCK_FILE"
flock -n 9
# While fd 9 holds the lock, calling deskflow_set_lock should skip and not toggle
deskflow_set_lock "locked"
if [ "$(deskflow_get_lock)" != "unlocked" ]; then
  echo "Error: deskflow_set_lock mutated state despite concurrent flock held!" >&2
  exit 1
fi
flock -u 9
exec 9>&-
echo "  -> deskflow_set_lock flock concurrency guard debounces: OK"

echo "=== [✓] ALL DESKFLOW COMPILER & CLIENT RUNNER TESTS PASSED! ==="
